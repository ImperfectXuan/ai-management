t_pass() { PASS=$((PASS + 1)); printf '  ok - %s\n' "$1"; }
t_fail() { FAIL=$((FAIL + 1)); printf '  NOT OK - %s\n' "$1"; }

expect_contains() {
  if grep -qF -- "$2" "$1" 2>/dev/null; then
    t_pass "$3"
  else
    t_fail "$3 (pattern missing: $2)"
  fi
}

expect_absent() {
  if grep -qF -- "$2" "$1" 2>/dev/null; then
    t_fail "$3 (unexpected pattern found: $2)"
  else
    t_pass "$3"
  fi
}

expect_json() {
  # $1=json string $2=jq path $3=expected $4=test name
  local actual
  actual="$(printf '%s' "$1" | jq -r "$2" 2>/dev/null)"
  if [ "$actual" = "$3" ]; then
    t_pass "$4"
  else
    t_fail "$4 (expected $3, got $actual)"
  fi
}

